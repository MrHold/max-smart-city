/** Приветствие на первый запуск, /start и /help. */
export function welcomeText(name?: string | null): string {
  const hello = name ? `Здравствуйте, ${name}! 👋` : 'Здравствуйте! 👋';
  return [
    hello,
    '',
    'Я — «Одна заявка на весь дом»: помогаю жителям решать проблемы в доме с управляющей компанией.',
    '',
    '🏠 Контакты УК, диспетчера и аварийной службы — с графиком: видно, кто на связи прямо сейчас',
    '📝 Заявка о проблеме — со сроком устранения по закону',
    '👥 «У меня тоже» — соседи присоединяются, и УК получает одну заявку с масштабом вместо десятков звонков',
    '💰 Сумма перерасчёта за время, пока услуги не было',
    '🔔 Уведомления сюда, в чат: заявку приняли, назначили мастера, работа выполнена',
    '',
    'Нажмите «Мой дом», чтобы начать.',
  ].join('\n');
}

